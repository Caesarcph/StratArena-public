function getLang() {
  const stored = localStorage.getItem('lang');
  return stored === 'zh' ? 'zh' : 'en';
}

function applyParams(text, params) {
  if (!params) return text;
  return Object.keys(params).reduce((acc, key) => acc.replaceAll(`{${key}}`, String(params[key])), text);
}

function t(key, params) {
  const lang = getLang();
  const value = TRANSLATIONS[lang]?.[key] ?? TRANSLATIONS.en?.[key] ?? key;
  return applyParams(value, params);
}

function tc(text) {
  if (text === null || text === undefined) return text;
  if (Array.isArray(text)) return text.map(tc);
  if (typeof text === 'object' && ('en' in text || 'zh' in text)) {
    const lang = getLang();
    return text[lang] ?? text.en ?? text.zh ?? '';
  }
  return text;
}

function translateContent(text) {
  return tc(text);
}

function updateStaticText() {
  document.documentElement.lang = getLang() === 'zh' ? 'zh-CN' : 'en';
  const map = {
    arena: 'nav.arena',
    'ea-arena': 'nav.ea_arena',
    strategies: 'nav.strategies',
    research: 'nav.research',
    favorites: 'nav.favorites',
    compare: 'nav.compare',
    methodology: 'nav.methodology',
    changelog: 'nav.changelog',
    about: 'nav.about'
  };
  document.querySelectorAll('.site-nav a').forEach((link) => {
    const route = link.dataset.route;
    const count = link.querySelector('[data-favorite-count]');
    if (!route || !map[route]) return;
    const label = t(map[route]);
    if (count) {
      count.outerHTML = `<span class="nav-count ${count.classList.contains('hidden') ? 'hidden' : ''}" data-favorite-count>${count.textContent || ''}</span>`;
      link.childNodes[0].textContent = `${label} `;
    } else {
      link.textContent = label;
    }
  });
  const logo = document.querySelector('.logo');
  if (logo) logo.textContent = t('meta.site_name');
  const footerBrand = document.querySelector('.footer-brand');
  if (footerBrand) footerBrand.textContent = t('footer.brand') || t('meta.site_name');
  const footerNote = document.querySelector('.footer-note');
  if (footerNote) footerNote.textContent = getLang() === 'zh' ? '系统化策略与 MQL5 EA 研究竞技场。不构成投资建议。' : 'Research arena for systematic strategies and MQL5 EAs. Not financial advice.';
  const footerLinks = document.querySelectorAll('.footer-links a');
  const footerKeys = ['nav.research', 'nav.methodology', 'nav.about', 'nav.faq', 'nav.privacy', 'nav.terms'];
  footerLinks.forEach((link, index) => {
    const key = footerKeys[index];
    if (key) link.textContent = t(key);
  });
  const langToggle = document.getElementById('lang-toggle');
  const langLabel = document.getElementById('lang-label');
  if (langToggle) langToggle.setAttribute('aria-label', t('nav.switch_language'));
  if (langLabel) langLabel.textContent = getLang() === 'en' ? '中文' : 'EN';
}

function bindLangToggle() {
  const langToggle = document.getElementById('lang-toggle');
  if (!langToggle || langToggle.dataset.bound === '1') return;
  langToggle.dataset.bound = '1';
  langToggle.addEventListener('click', () => {
    setLang(getLang() === 'en' ? 'zh' : 'en');
  });
}

function setLang(lang) {
  const next = lang === 'zh' ? 'zh' : 'en';
  localStorage.setItem('lang', next);
  window.LANG = next;
  updateStaticText();
  bindLangToggle();
  if (typeof window.setTheme === 'function') {
    window.setTheme(document.documentElement.getAttribute('data-theme') || 'light');
  }
  if (typeof window.render === 'function') {
    window.render();
  }
}

document.addEventListener('DOMContentLoaded', () => {
  updateStaticText();
  bindLangToggle();
});

window.t = t;
window.tc = tc;
window.setLang = setLang;
window.getLang = getLang;
